-- ─── Types ────────────────────────────────────────────────────────────────────

create type public.quiz_visibility as enum ('private', 'unlisted', 'public');

-- ─── Helpers ──────────────────────────────────────────────────────────────────

create function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- ─── Profiles (hosts) ─────────────────────────────────────────────────────────

create table public.profiles (
  id           uuid primary key references auth.users (id) on delete cascade,
  display_name text not null check (char_length(display_name) between 1 and 80),
  avatar_url   text,
  created_at   timestamptz not null default now()
);

-- New sign-ups get a profile. Anonymous users (quiz participants, P2) don't.
create function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if coalesce(new.is_anonymous, false) then
    return new;
  end if;
  insert into public.profiles (id, display_name, avatar_url)
  values (
    new.id,
    left(coalesce(
      nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''),
      nullif(trim(new.raw_user_meta_data ->> 'name'), ''),
      nullif(split_part(coalesce(new.email, ''), '@', 1), ''),
      'Guru'
    ), 80),
    new.raw_user_meta_data ->> 'avatar_url'
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ─── Quizzes ──────────────────────────────────────────────────────────────────

create table public.quizzes (
  id                    uuid primary key default gen_random_uuid(),
  owner_id              uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  title                 text not null default '' check (char_length(title) <= 150),
  description           text not null default '' check (char_length(description) <= 2000),
  cover_url             text,
  theme                 jsonb not null default '{}',
  visibility            public.quiz_visibility not null default 'private',
  slug                  text unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  embed_allowed_origins text[] not null default '{}',
  -- Bumped by every save; saves and publishes must name the revision they build on.
  draft_revision        int not null default 0,
  -- draft_revision that the latest version was published from (null = never published).
  published_revision    int,
  latest_version        int,
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now()
);

create index quizzes_owner_updated_idx on public.quizzes (owner_id, updated_at desc);

create trigger quizzes_set_updated_at
  before update on public.quizzes
  for each row execute function public.set_updated_at();

-- ─── Questions (the editable draft) ───────────────────────────────────────────

create table public.questions (
  id           uuid primary key,  -- generated by the editor (crypto.randomUUID)
  quiz_id      uuid not null references public.quizzes (id) on delete cascade,
  position     int  not null check (position >= 0),
  type         text not null check (type ~ '^[a-z][a-z_]*$'),
  prompt       text not null default '' check (char_length(prompt) <= 2000),
  help         text not null default '' check (char_length(help) <= 1000),
  media        jsonb not null default '[]' check (jsonb_typeof(media) = 'array'),
  config       jsonb not null check (jsonb_typeof(config) = 'object'),
  time_limit_s int check (time_limit_s between 5 and 600),
  points       int  not null default 1000 check (points between 0 and 10000),
  explanation  text not null default '' check (char_length(explanation) <= 2000),
  tags         text[] not null default '{}',
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create index questions_quiz_position_idx on public.questions (quiz_id, position);

create trigger questions_set_updated_at
  before update on public.questions
  for each row execute function public.set_updated_at();

-- ─── Published versions (immutable snapshots) ─────────────────────────────────

create table public.quiz_versions (
  id           uuid primary key default gen_random_uuid(),
  quiz_id      uuid not null references public.quizzes (id) on delete cascade,
  version      int  not null check (version >= 1),
  snapshot     jsonb not null,
  published_at timestamptz not null default now(),
  unique (quiz_id, version)
);

